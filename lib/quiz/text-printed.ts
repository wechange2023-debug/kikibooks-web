/**
 * 삽화에 본문 문장이 인쇄된 계보 판정 (Q-0 실측 · ADR-0065 Amd#2 D-B3 QB-1·QB-2).
 *
 * 문항 ③(그림 보고 문장 찾기)은 **정답 문장이 그림 안에 인쇄돼 있으면 성립하지 않는다.**
 * 보기를 고를 필요 없이 그림에 적힌 글자를 읽으면 끝이기 때문이다.
 *
 * ──────────────────────────────────────────────────────────────────────────────
 * 실측 근거 (`scripts/quiz_pilot/Q0_measure_report.md` §3.2·§3.3·§7)
 * ──────────────────────────────────────────────────────────────────────────────
 *   Book Dash 190권은 slug 형태로 두 계보다.
 *     kebab-slug (`moms-hands` 등) 151권 → 삽화에 본문 문장 **인쇄됨**
 *     UUID-slug  (`9c9e6e52-…`)    39권 → **미인쇄**
 *   ASb 527권·Bloom 141권은 표본 전량 미인쇄.
 *
 *   검증: 표본 **69면 / 35권**(190권의 18.4%)에서 **반례 0건**.
 *   팀장 확정(QB-2, 2026-08-21) — 전수 육안 대신 이 규칙을 **정본으로 승격**한다.
 *
 * ★ 한계: 표본 검증이지 전수 확인이 아니다. book_dash 신규 적재 시 같은 규칙이
 *   유지되는지 재확인해야 한다(리포트 §7.3).
 *
 * ★ ①에는 적용하지 않는다(QB-1 팀장 확정). ①은 듣지 않고 글자만 봐도 맞출 수 있으나
 *   유출 강도가 읽기 능력에 좌우돼 만 3~7세에게는 약하다고 판단했다. ②는 순서 정보가
 *   아니므로 애초에 무관하다.
 */

/** 표준 UUID 앞머리 — `source_id`가 이 형태면 UUID 계보다. */
const UUID_PREFIX_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-/i;

/** 문장 인쇄 계보를 가진 유일한 소스. 다른 플랫폼은 표본 전량 미인쇄였다. */
const PRINTED_PLATFORM = 'book_dash';

/**
 * 이 책의 삽화에 본문 문장이 인쇄돼 있는가.
 *
 * @returns true면 문항 ③을 출제하지 않는다(858 → 707권).
 */
export function isTextPrintedOnImages(book: {
  source_platform: string;
  source_id: string;
}): boolean {
  return (
    book.source_platform === PRINTED_PLATFORM &&
    !UUID_PREFIX_RE.test(book.source_id)
  );
}
